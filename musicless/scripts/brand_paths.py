"""Write src/film/parts/logoPaths.ts from the Musicless brand files (public/brand), so the film can draw the
logos itself and snap the note the way the extension's first-run page does.
usage: brand_paths.py"""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
BRAND = ROOT / "public/brand"

def logo(name):
    s = (BRAND / name).read_text()
    view = re.search(r'viewBox="([^"]+)"', s).group(1)
    mark = word = None
    for attrs in re.findall(r"<path([^>]*)>", s):
        d = re.search(r'\sd="([^"]+)"', attrs).group(1)
        tf = re.search(r'transform="matrix\(([^)]+)\)"', attrs)
        if tf:
            mark = [float(v) for v in tf.group(1).split()]
        else:
            word = d
    assert mark and word, name
    return {"viewBox": [float(v) for v in view.split()], "mark": mark, "word": word}

